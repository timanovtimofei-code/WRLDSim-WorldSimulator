SAFE = ("не ", "отказ", "без ", "мирно", "мирн", "легальн", "законн", "официальн", "осторожн", "перегов")
HEAVY = ("всех", "массов", "президент", "министр", "полици", "арми", "судь", "банк", "мэр")
MIN_LEN = 4


def _compile(stems):
    # «ё» приводится к «е», чтобы не зависеть от того, как игрок набирает текст.
    return re.compile(r"(?<![а-яa-z0-9])(?:" + "|".join(re.escape(s.replace("ё", "е")) for s in stems) + ")")


_PATTERNS = [(_compile(stems), risk, reason, cheats) for stems, risk, reason, cheats in RULES]
_SAFE, _HEAVY = _compile(SAFE), _compile(HEAVY)


def assess(text):
    t = " ".join(text.lower().replace("ё", "е").split())
    if len(t) < MIN_LEN:
        return Assessment(0, "", ())
    hits = [(risk, reason, cheats) for pattern, risk, reason, cheats in _PATTERNS if pattern.search(t)]
    if not hits:
        return Assessment(0, "", ())
    hits.sort(key=lambda h: -h[0])
    risk = hits[0][0] + 6 * min(len(hits) - 1, 2) + 4 * min(len(_HEAVY.findall(t)), 2)
    if _SAFE.search(t):
        risk *= 0.45
    return Assessment(min(int(risk), 99), hits[0][1], hits[0][2])
